#!/usr/bin/env python3
"""Generate the committed LVGL 8 font from JetBrains Mono. Requires Pillow."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
import argparse
parser = argparse.ArgumentParser()
parser.add_argument('--size', type=int, choices=(16, 40), default=16)
size = parser.parse_args().size
font = ImageFont.truetype(str(ROOT / 'assets/fonts/JetBrainsMono-Medium.ttf'), size)
advance = round(font.getlength('M')) * 16
bitmap = []
glyphs = ['    {0, 0, 0, 0, 0, 0}']
for code in [*range(32, 127), 0x00B0]:
    character = chr(code)
    left, top, right, bottom = font.getbbox(character, anchor='ls')
    width, height = right - left, bottom - top
    image = Image.new('L', (width, max(height, 1)))
    ImageDraw.Draw(image).text((-left, -top), character, font=font, anchor='ls', fill=255)
    samples = [(v * 15 + 127) // 255 for v in image.tobytes()][:width * height]
    offset = len(bitmap)
    for i in range(0, len(samples), 2):
        bitmap.append((samples[i] << 4) | (samples[i + 1] if i + 1 < len(samples) else 0))
    glyphs.append(f'    {{{offset}, {advance}, {width}, {height}, {left}, {-bottom}}}')
lines = [', '.join(f'0x{v:02x}' for v in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16)]
source = '''// Generated by scripts/generate_panel_font.py. JetBrains Mono: assets/fonts/OFL.txt.
#include <lvgl.h>

static const uint8_t bitmap[] = {
'''
source += '\n'.join('    ' + line + ',' for line in lines)
source += '\n};\nstatic const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {\n' + ',\n'.join(glyphs) + '\n};\n'
source += '''static const lv_font_fmt_txt_cmap_t cmaps[] = {
    {.range_start = 32, .range_length = 95, .glyph_id_start = 1,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},
    {.range_start = 0x00B0, .range_length = 1, .glyph_id_start = 96,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}
};
static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t descriptor = {
    .glyph_bitmap = bitmap, .glyph_dsc = glyphs, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 2, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0, .cache = &cache
};
const lv_font_t panel_mono_16 = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 20, .base_line = 4, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2, .underline_thickness = 1, .dsc = &descriptor
};
'''
source = source.replace('panel_mono_16', f'panel_mono_{size}')
source = source.replace('.line_height = 20, .base_line = 4', f'.line_height = {size + size // 4}, .base_line = {size // 4}')
filename = 'panel_font.c' if size == 16 else 'panel_clock_font.c'
(ROOT / 'src' / filename).write_text(source)
print(f'Generated {len(bitmap)} bytes of glyph bitmaps')
